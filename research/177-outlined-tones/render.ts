/**
 * #177: writes figures/c-h3world.sumi.yaml from #173's H3-World figure
 * (research/173-paper-theme/figures/c-h3world.sumi.yaml, not changed) with
 * outlined tones and edge tones where the original figure has colored frames,
 * text and lines, then renders it with `paper` and, for comparison, with
 * `--theme color`:
 *   render (PDF) -> PNG at 200dpi (pdftoppm) -> 64-colour preview (magick).
 *
 * Usage (from the repository root): bun research/177-outlined-tones/render.ts
 *
 * Every rewrite must match exactly as often as stated, so a change to #173's
 * figure fails here instead of silently producing another figure. Writes
 * PDFs and full PNGs under out/ (ignored) and the committed previews
 * previews/c-h3world.png and previews/c-h3world.color.png.
 */

import { mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const here = import.meta.dir;
const root = join(here, "../..");
const source = join(root, "research/173-paper-theme/figures/c-h3world.sumi.yaml");
const figure = join(here, "figures/c-h3world.sumi.yaml");
const out = join(here, "out");
const previews = join(here, "previews");
mkdirSync(out, { recursive: true });
mkdirSync(previews, { recursive: true });

let text = readFileSync(source, "utf8");

/** Replaces `pattern` (exactly `count` matches) with `replacement`. */
function rewrite(
  pattern: RegExp,
  replacement: string | ((...m: string[]) => string),
  count: number,
) {
  const matches = text.match(new RegExp(pattern.source, `${pattern.flags.replace("g", "")}g`));
  if ((matches?.length ?? 0) !== count) {
    throw new Error(`${pattern}: expected ${count} matches, found ${matches?.length ?? 0}`);
  }
  text = text.replace(
    new RegExp(pattern.source, `${pattern.flags.replace("g", "")}g`),
    replacement as string,
  );
}

const HEADER = `# #177: research/173-paper-theme/figures/c-h3world.sumi.yaml with outlined
# tones and edge tones where the original figure (the user's own H3-World
# figure, not committed) has colored frames, text and lines. GENERATED by
# research/177-outlined-tones/render.ts: edit the script, not this file.
# - H3 Encoders and the Visual VAE Encoder: variant outlined (purple, orange)
# - keys: outlined, orange (W A S D) and blue (I F J K L); pressed keys
#   keep their tone with variant filled
# - the token rows of (a) and (b) as tokens nodes (#181) with outlined
#   cells: Static, I0 and Pad gray, A purple, V orange
# - edges: frames → VAE → V… orange; LoRA → ⊕ pink; QKV / Out Proj. → ⊕ blue
`;
text = HEADER + text;

// Encoders and the VAE: white with a colored frame and text.
rewrite(/(label: H3 Encoder, tone: purple)/, "$1, variant: outlined", 6);
rewrite(/(label: "Visual\\nVAE\\nEncoder", tone: orange)/, "$1, variant: outlined", 1);

// Keys: outlined in the cluster's color; a pressed key is filled with its tone.
rewrite(
  /\{ id: (k\d-([wasdifjkl])), component: square, label: ([A-Z])(, tone: (orange|blue))?, props: \{ width: 11pt, height: 11pt \} \}/,
  (_m, id, key, label, _t, tone) => {
    const cluster = "wasd".includes(key ?? "") ? "orange" : "blue";
    const style =
      tone === undefined ? `tone: ${cluster}, variant: outlined` : `tone: ${tone}, variant: filled`;
    return `{ id: ${id}, component: square, label: ${label}, ${style}, props: { width: 11pt, height: 11pt } }`;
  },
  45,
);

// The token rows as tokens with outlined cells.
const SEQ = [
  "static",
  "a1",
  "a2",
  "a3",
  "a4",
  "a5",
  "adots",
  "i0",
  "v1",
  "v2",
  "v3",
  "v4",
  "v5",
  "vdots",
];
const BT = ["static", "a1", "a2", "a3", "i0", "v1", "v2", "v3", "pad"];
rewrite(/- row: \{ gap: 1\.5pt, items: \[ seq-static, [^\]]*\] \}/, "- seq", 1);
rewrite(/- row: \{ gap: 1pt, items: \[ bt-static, [^\]]*\] \}/, "- bt", 1);
const cellLines = (prefix: string, ids: string[]) => {
  const cells: string[] = [];
  for (const id of ids) {
    const pattern = new RegExp(
      `  - \\{ id: ${prefix}-${id}, component: box, label: ('[^']*'|[A-Za-z]+)(, tone: (purple|orange))?, props: \\{ width: (\\d+pt), height: 14pt \\} \\}\\n`,
    );
    const match = pattern.exec(text);
    if (match === null) throw new Error(`no cell ${prefix}-${id}`);
    text = text.replace(pattern, "");
    const tone = match[3] ?? "gray";
    cells.push(`        - { id: ${id}, label: ${match[1]}, tone: ${tone}, width: ${match[4]} }`);
  }
  return cells;
};
const seqCells = cellLines("seq", SEQ);
const btCells = cellLines("bt", BT);
const tokens = (id: string, gap: string, cells: string[]) =>
  [
    `  - id: ${id}`,
    "    component: tokens",
    "    props:",
    `      gap: ${gap}`,
    "      height: 14pt",
    "      variant: outlined",
    "      cells:",
    ...cells,
    "",
  ].join("\n");
// A function, so the `$` of the labels' math is not read as a replacement pattern.
rewrite(
  /( {2}- \{ id: b-block1, )/,
  (m) => `${tokens("seq", "1.5pt", seqCells)}${tokens("bt", "1pt", btCells)}${m}`,
  1,
);
rewrite(/\[ seq-heading, seq-static \]/, "[ seq-heading, seq.static ]", 1);
rewrite(/\{ from: refiner, to: seq-a5 \}/, "{ from: refiner, to: seq.a5 }", 1);
rewrite(/\{ from: bt-a3, to: b-block1 \}/, "{ from: bt.a3, to: b-block1 }", 1);

// Colored edges.
rewrite(/(\{ from: frames-more, to: vae, toAnchor: "west:0\.1")/, "$1, tone: orange", 1);
rewrite(
  /\{ from: vae, to: seq-vdots, (fromAnchor: south, toAnchor: east) \}/,
  "{ from: vae, to: seq.vdots, $1, tone: orange }",
  1,
);
// As in the original, the two colors enter ⊕ from above and below: merged
// into one point (fanIn: merge), lines of two colors would overlap.
rewrite(/(\{ from: lora-(in|out), to: c-add-(in|out))/, "$1, toAnchor: north, tone: pink", 2);
rewrite(/(\{ from: (qkv|out-proj), to: c-add-(in|out))/, "$1, toAnchor: south, tone: blue", 2);

writeFileSync(figure, text);
console.log(`Wrote ${figure.slice(root.length + 1)}`);

/** Runs a tool that must succeed (pdftoppm, magick). */
function run(args: string[]): void {
  const result = Bun.spawnSync(args, { cwd: root, stdout: "pipe", stderr: "pipe" });
  if (result.exitCode !== 0) {
    throw new Error(`${args.join(" ")} failed:\n${result.stderr.toString()}`);
  }
}

interface RenderReport {
  diagnostics: { code: string; severity: string; message: string }[];
  size?: { widthMm: number; heightMm: number; scale?: number };
}

for (const theme of ["paper", "color"]) {
  const base = theme === "paper" ? "c-h3world" : `c-h3world.${theme}`;
  const pdf = join(out, `${base}.pdf`);
  rmSync(pdf, { force: true });
  const args = ["bun", "src/cli/index.ts", "render", figure, "--theme", theme, "--json", "-o", pdf];
  const result = Bun.spawnSync(args, { cwd: root, stdout: "pipe", stderr: "pipe" });
  const report = JSON.parse(result.stdout.toString() || "{}") as RenderReport;
  const errors = (report.diagnostics ?? []).filter((d) => d.severity === "error");
  // The color theme's larger fills make the figure too wide (as #173's comparison).
  if (result.exitCode > 1 || (theme === "paper" && errors.length > 0)) {
    throw new Error(`${args.join(" ")}: exit ${result.exitCode}\n${result.stdout}${result.stderr}`);
  }
  const counts = new Map<string, number>();
  for (const d of report.diagnostics ?? []) {
    const key = `${d.severity} ${d.code}`;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  console.log(
    `${base}: ${report.size?.widthMm} × ${report.size?.heightMm}mm, scale ${report.size?.scale ?? 1}; ` +
      ([...counts].map(([key, n]) => `${key} ×${n}`).join(", ") || "no diagnostics"),
  );
  rmSync(join(out, `${base}.png`), { force: true });
  run(["pdftoppm", "-r", "200", "-png", "-singlefile", pdf, join(out, base)]);
  const preview = join(previews, `${base}.png`);
  run(["magick", join(out, `${base}.png`), "-colors", "64", preview]);
  console.log(`  ${preview.slice(root.length + 1)}: ${statSync(preview).size} bytes`);
}
