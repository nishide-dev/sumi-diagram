/**
 * Helpers for the patched copies of product modules (#124). A copy is the
 * checked-out `src/` file with textual patches that must each match exactly
 * once, written to `out/` (gitignored) with its relative imports pointing
 * back at `src/`. The product source is never modified.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

export const ROOT = join(import.meta.dir, "../..");
export const OUT = join(import.meta.dir, "out");

export const HEADER = "// @ts-nocheck generated by research/124-stage-b; do not edit\n";

/** Replaces `find` (which must occur exactly once) with `replace`. */
export function patch(source: string, find: string, replace: string): string {
  const count = source.split(find).length - 1;
  if (count !== 1) throw new Error(`patch target found ${count} times: ${find}`);
  return source.replace(find, replace);
}

/** Reads `src/<path>` with every relative import rewritten to resolve from `out/`. */
export function readProduct(path: string): string {
  const dir = dirname(join(ROOT, path));
  return readFileSync(join(ROOT, path), "utf8").replace(
    /from "(\.\.?\/[^"]*)"/g,
    (_m, rel: string) => {
      const target = relative(OUT, resolve(dir, rel));
      return `from "${target.startsWith(".") ? target : `./${target}`}"`;
    },
  );
}

/** Writes a patched copy to `out/<name>` and returns its path. */
export function writeCopy(name: string, text: string): string {
  mkdirSync(OUT, { recursive: true });
  const file = join(OUT, name);
  writeFileSync(file, `${HEADER}${text}`);
  return file;
}
