/**
 * #180: writes figures/c-h3world.sumi.yaml from #177's H3-World figure
 * (research/177-outlined-tones/figures/c-h3world.sumi.yaml, not changed) with
 * the masked-attention matrix of (c) written as one `matrix` node instead of
 * a group of 81 cell boxes and 19 header labels, and its legend made from
 * the matrix's classes, then renders it with `paper` and, for comparison,
 * with `--theme color`:
 *   render (PDF) -> PNG at 200dpi (pdftoppm) -> 64-colour preview (magick).
 *
 * Usage (from the repository root): bun research/180-matrix/render.ts
 *
 * The cells' classes are read from #177's boxes (green → o, orange → L,
 * no tone → masked), so the matrix says exactly what the hand-written one
 * did. Every rewrite must match exactly as often as stated, so a change to
 * #177's figure fails here instead of silently producing another figure.
 * Writes PDFs and full PNGs under out/ (ignored) and the committed previews
 * previews/c-h3world.png and previews/c-h3world.color.png.
 */

import { mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const here = import.meta.dir;
const root = join(here, "../..");
const source = join(root, "research/177-outlined-tones/figures/c-h3world.sumi.yaml");
const figure = join(here, "figures/c-h3world.sumi.yaml");
const out = join(here, "out");
const previews = join(here, "previews");
mkdirSync(out, { recursive: true });
mkdirSync(previews, { recursive: true });

let text = readFileSync(source, "utf8");

/** Replaces `pattern` (exactly `count` matches) with `replacement`. */
function rewrite(
  pattern: RegExp,
  replacement: string | ((...m: string[]) => string),
  count: number,
) {
  const global = new RegExp(pattern.source, `${pattern.flags.replace("g", "")}g`);
  const matches = text.match(global);
  if ((matches?.length ?? 0) !== count) {
    throw new Error(`${pattern}: expected ${count} matches, found ${matches?.length ?? 0}`);
  }
  text = text.replace(global, replacement as string);
}

const HEADER = `# #180: research/177-outlined-tones/figures/c-h3world.sumi.yaml with the
# masked-attention matrix of (c) written as one matrix node (81 cells in 9
# rows of classes, toned row and column headers, 1.5pt between cells) and the
# legend next to it made from the matrix's classes ({ class: mask.o }, …);
# the column of tokens of (c) as a tokens node (#181), as research/181-tokens.
# GENERATED by research/180-matrix/render.ts: edit the script, not this file.
`;
text = HEADER + text;

// 1. The cells' classes, from #177's boxes.
const SIDE = 9;
const rows: string[] = [];
for (let r = 0; r < SIDE; r++) {
  let row = "";
  for (let c = 0; c < SIDE; c++) {
    const pattern = new RegExp(
      `  - \\{ id: m-${r}-${c}, component: box(, tone: (green|orange))?, props: \\{ width: 12pt, height: 9pt \\} \\}\\n`,
    );
    const match = pattern.exec(text);
    if (match === null) throw new Error(`no cell m-${r}-${c}`);
    text = text.replace(pattern, "");
    row += match[2] === "green" ? "o" : match[2] === "orange" ? "L" : ".";
  }
  rows.push(row);
}

// 2. The headers, from #177's labels (the same text on both sides).
const headers: string[] = [];
for (let i = 0; i < SIDE; i++) {
  for (const prefix of ["mc", "mr"]) {
    const pattern = new RegExp(
      `  - \\{ id: ${prefix}-${i}, component: label, label: ('[^']*'), props: \\{ width: (12|22)pt \\} \\}\\n`,
    );
    const match = pattern.exec(text);
    if (match === null) throw new Error(`no header ${prefix}-${i}`);
    text = text.replace(pattern, "");
    if (prefix === "mc") headers.push(match[1] as string);
  }
}
rewrite(
  / {2}- \{ id: mc-corner, component: label, label: Q \/ K, props: \{ width: 22pt \} \}\n/,
  "",
  1,
);
// As in the original: the action tokens' headers purple, the video tokens' orange.
const toned = headers.map((h) =>
  h.includes("A_")
    ? `{ label: ${h}, tone: purple }`
    : h.includes("V_")
      ? `{ label: ${h}, tone: orange }`
      : h,
);

// 3. The group of rows becomes the matrix node (same ID: the edges and the
// arrange tree still name "mask").
rewrite(/ {2}- id: mask\n {4}variant: plain\n {4}arrange:\n(?: {6,}.*\n)+/, "", 1);
const matrix = [
  "  - id: mask",
  "    component: matrix",
  "    props:",
  "      corner: Q / K",
  `      rows: [ ${toned.join(", ")} ]`,
  `      columns: [ ${toned.join(", ")} ]`,
  "      cellWidth: 12pt",
  "      cellHeight: 9pt",
  "      gap: 1.5pt",
  "      variant: filled",
  "      classes:",
  "        o: { tone: green, label: Allowed }",
  '        L: { tone: orange, label: "A↔V Link" }',
  "        .: { pattern: hatch, label: Masked }",
  "      cells:",
  ...rows.map((row) => `        - "${row}"`),
  "",
].join("\n");
// A function, so the `$` of the labels' math is not read as a replacement pattern.
rewrite(/( {2}- \{ id: mask-title, )/, (m) => `${matrix}${m}`, 1);

// 4. The legend from the classes.
rewrite(
  / {8}- \{ node: \{ tone: green \}, label: Allowed \}\n {8}- \{ node: \{ tone: orange \}, label: "A↔V Link" \}\n {8}- \{ node: \{ component: box \}, label: Masked \}\n/,
  "        - { class: mask.o }\n        - { class: mask.L }\n        - { class: mask.. }\n",
  1,
);

// 5. The column of tokens left of the LoRA as a tokens node (#181), as
// research/181-tokens did: its 9 blank cells were lint/empty-label too.
const CT_TONES = [
  "gray",
  "purple",
  "purple",
  "purple",
  "gray",
  "orange",
  "orange",
  "orange",
  "gray",
];
const ct = `  - { id: ct, component: tokens, props: { direction: down, gap: 1.5pt, width: 9pt, height: 7pt, variant: filled, cells: [ ${CT_TONES.map((t) => `{ tone: ${t} }`).join(", ")} ] } }\n`;
for (const [i, tone] of CT_TONES.entries()) {
  rewrite(
    new RegExp(
      ` {2}- \\{ id: ct-${i}, component: box, tone: ${tone}, props: \\{ width: 9pt, height: 7pt \\}, variant: filled \\}\\n`,
    ),
    i === 0 ? ct : "",
    1,
  );
}
rewrite(/- stack: \{ gap: 1\.5pt, items: \[ ct-0, [^\]]*\] \}/, "- ct", 1);
rewrite(/\{ from: ct-4, /, "{ from: ct.5, ", 2);

writeFileSync(figure, text);
console.log(`Wrote ${figure.slice(root.length + 1)}`);

/** Runs a tool that must succeed (pdftoppm, magick). */
function run(args: string[]): void {
  const result = Bun.spawnSync(args, { cwd: root, stdout: "pipe", stderr: "pipe" });
  if (result.exitCode !== 0) {
    throw new Error(`${args.join(" ")} failed:\n${result.stderr.toString()}`);
  }
}

interface RenderReport {
  diagnostics: { code: string; severity: string; message: string }[];
  size?: { widthMm: number; heightMm: number; scale?: number };
}

for (const theme of ["paper", "color"]) {
  const base = theme === "paper" ? "c-h3world" : `c-h3world.${theme}`;
  const pdf = join(out, `${base}.pdf`);
  rmSync(pdf, { force: true });
  const args = ["bun", "src/cli/index.ts", "render", figure, "--theme", theme, "--json", "-o", pdf];
  const result = Bun.spawnSync(args, { cwd: root, stdout: "pipe", stderr: "pipe" });
  const report = JSON.parse(result.stdout.toString() || "{}") as RenderReport;
  const errors = (report.diagnostics ?? []).filter((d) => d.severity === "error");
  // The color theme's larger fills make the figure too wide (as #173's comparison).
  if (result.exitCode > 1 || (theme === "paper" && errors.length > 0)) {
    throw new Error(`${args.join(" ")}: exit ${result.exitCode}\n${result.stdout}${result.stderr}`);
  }
  const counts = new Map<string, number>();
  for (const d of report.diagnostics ?? []) {
    const key = `${d.severity} ${d.code}`;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  console.log(
    `${base}: ${report.size?.widthMm} × ${report.size?.heightMm}mm, scale ${report.size?.scale ?? 1}; ` +
      ([...counts].map(([key, n]) => `${key} ×${n}`).join(", ") || "no diagnostics"),
  );
  rmSync(join(out, `${base}.png`), { force: true });
  run(["pdftoppm", "-r", "200", "-png", "-singlefile", pdf, join(out, base)]);
  const preview = join(previews, `${base}.png`);
  run(["magick", join(out, `${base}.png`), "-colors", "64", preview]);
  console.log(`  ${preview.slice(root.length + 1)}: ${statSync(preview).size} bytes`);
}
