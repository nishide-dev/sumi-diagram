/** Path of a repository file relative to the gallery directory. */
const rel = (path: string) => posix.relative(GALLERY_DIR, path);

const anchor = (entry: CatalogEntry) => entry.id.replace("/", "-");

/** Manifest fields other than the common ones, e.g. `shape`, `direction`, `head`. */
function manifestFields(entry: CatalogEntry): [string, string][] {
  const common = new Set([
    "id",
    "kind",
    "namespace",
    "name",
    "description",
    "variants",
    "since",
    "props",
    "deprecated",
  ]);
  return Object.entries(entry)
    .filter(([key, value]) => !common.has(key) && value !== undefined)
    .map(([key, value]) => [key, typeof value === "string" ? value : JSON.stringify(value)]);
}

interface PropRow {
  name: string;
  type: string;
  required: boolean;
  description: string;
}

/** A summary of the props JSON Schema: one row per property. */
function propRows(entry: CatalogEntry): PropRow[] {
  const schema = entry.props as {
    properties?: Record<string, { type?: unknown; enum?: unknown[]; description?: string }>;
    required?: string[];
  };
  return Object.entries(schema.properties ?? {}).map(([name, prop]) => ({
    name,
    type:
      prop.enum !== undefined
        ? prop.enum.map((v) => JSON.stringify(v)).join(" | ")
        : Array.isArray(prop.type)
          ? prop.type.join(" | ")
          : String(prop.type ?? "any"),
    required: schema.required?.includes(name) ?? false,
    description: prop.description ?? "",
  }));
}

function sizeText(outcome: RenderOutcome): string {
  if (outcome.widthPt === undefined || outcome.heightPt === undefined) return "not rendered";
  const limits = [
    ...(outcome.maxWidthPt === undefined ? [] : [`max width ${formatMm(outcome.maxWidthPt)}`]),
    ...(outcome.maxHeightPt === undefined ? [] : [`max height ${formatMm(outcome.maxHeightPt)}`]),
  ];
  const limit = limits.length === 0 ? "" : ` (${limits.join(", ")})`;
  return `${formatMm(outcome.widthPt)} × ${formatMm(outcome.heightPt)}${limit}`;
}

/** Distinct diagnostic codes with their first message, errors first (input is sorted). */
function diagnosticSummary(diagnostics: readonly Diagnostic[]): string[] {
  const seen = new Map<string, { severity: string; message: string; count: number }>();
  for (const d of diagnostics) {
    const entry = seen.get(d.code);
    if (entry) entry.count++;
    else seen.set(d.code, { severity: d.severity, message: d.message, count: 1 });
  }
  return [...seen].map(
    ([code, { severity, message, count }]) =>
      `${severity} ${code}${count > 1 ? ` (×${count})` : ""}: ${message}`,
  );
}

function renderCommand(file: string, outcome: RenderOutcome): string {
  const { theme, profile } = outcome.rendering.overrides;
  return [
    "sumi render",
    file,
    ...(theme === undefined ? [] : [`--theme ${theme}`]),
    ...(profile === undefined ? [] : [`--profile ${profile}`]),
  ].join(" ");
}

