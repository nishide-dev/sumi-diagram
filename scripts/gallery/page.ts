function mdCompare(model: GalleryModel): string {
  const lines = [
    "## Profiles",
    "",
    `| ${PROFILE_HEADER.join(" | ")} |`,
    `| ${PROFILE_HEADER.map(() => "---").join(" | ")} |`,
    ...profileRows().map(
      ([id, ...rest]) => `| ${mdCode(id ?? "")} | ${rest.map(mdText).join(" | ")} |`,
    ),
    "",
    "## One figure, every theme × profile",
    "",
    mdInline(COMPARISON_NOTE),
    "",
    `| theme \\ profile | ${PROFILES.map(mdCode).join(" | ")} |`,
    `| --- | ${PROFILES.map(() => "---").join(" | ")} |`,
  ];
  for (const theme of THEMES) {
    const cells = PROFILES.map((profile) => {
      const o = model.comparison.outcomes.find(
        (x) => x.rendering.theme === theme && x.rendering.profile === profile,
      );
      return o === undefined
        ? ""
        : `${mdImage(o, `${model.comparison.source}, ${theme}, ${profile}`, GALLERY_DIR)}<br>${mdCode(renderCommand(model.comparison.source, o))}<br>${mdCaption(o)}`;
    });
    lines.push(`| ${mdCode(theme)} | ${cells.join(" | ")} |`);
  }
  lines.push("");
  return mdTopic("Profiles and comparison", undefined, lines);
}

function mdIndex(model: GalleryModel): string {
  // GitHub's old heading slugs must survive the move to individual pages.
  const headingSlug = (title: string) =>
    title
      .toLowerCase()
      .replace(/[^\p{L}\p{N}_\- ]/gu, "")
      .replaceAll(" ", "-");
  const legacyAnchor = (title: string) => `<a id="${escapeHtml(headingSlug(title))}"></a>`;
  const topicAnchors: Record<string, string[]> = {
    "examples.md": ["Examples"],
    "themes.md": ["Themes and profiles"],
    "tones.md": ["Tones"],
    "dim.md": ["Dimmed groups"],
    "compare.md": ["Profiles", "One figure, every theme × profile"],
  };
  return [
    "# Sumi gallery",
    "",
    `> ${mdInline(GENERATED_NOTE)} Everything on one page: [${mdCode("index.html")}](index.html).`,
    "",
    "## Topics",
    "",
    ...TOPICS.flatMap(([file, title, line]) => [
      `- ${(topicAnchors[file] ?? []).map(legacyAnchor).join("")}[${mdText(title)}](${file}): ${mdInline(line)}`,
      ...(file === "examples.md"
        ? model.examples.map(
            ({ title }) =>
              `  - ${legacyAnchor(title)}[${mdText(title)}](examples.md#${headingSlug(title)})`,
          )
        : []),
      ...(file === "tones.md"
        ? ["Solid and tinted tones", "Outlined tones and edge tones"].map(
            (title) => `  - ${legacyAnchor(title)}[${title}](tones.md#${headingSlug(title)})`,
          )
        : []),
    ]),
    "",
    "## Components",
    "",
    mdInline(
      "Every built-in component with every variant, under every built-in theme. Each page has the component's props and the YAML that draws its samples.",
    ),
    "",
    "| component | kind | description |",
    "| --- | --- | --- |",
    ...model.components.map(
      ({ sample }) =>
        `| ${legacyAnchor(sample.entry.id)}[${mdText(sample.entry.id)}](${componentPage(sample.entry)}) | ${mdText(sample.entry.kind)} | ${mdInline(sample.entry.description)} |`,
    ),
    "",
  ].join("\n");
}

/**
 * The Markdown pages: paths relative to the repository root and their text.
 * `README.md` is the index; every other page links back to it.
 */
export function galleryMarkdownPages(model: GalleryModel): Map<string, string> {
  const pages = new Map<string, string>();
  pages.set(`${GALLERY_DIR}/README.md`, mdIndex(model));
  for (const component of model.components) {
    pages.set(`${GALLERY_DIR}/${componentPage(component.sample.entry)}`, mdComponent(component));
  }
  pages.set(`${GALLERY_DIR}/examples.md`, mdExamples(model));
  pages.set(`${GALLERY_DIR}/themes.md`, mdThemes(model));
  pages.set(`${GALLERY_DIR}/tones.md`, mdTones(model));
  pages.set(`${GALLERY_DIR}/dim.md`, mdDim(model));
  pages.set(`${GALLERY_DIR}/compare.md`, mdCompare(model));
  return pages;
}
