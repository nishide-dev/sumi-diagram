function htmlFigure(outcome: RenderOutcome, caption: string, alt: string): string {
  const diagnostics = diagnosticSummary(outcome.diagnostics);
  const body =
    outcome.svg === undefined
      ? `<p class="failed">Not rendered: rejected before drawing (see below).</p>`
      : `<img src="${urlAttribute(rel(outcome.rendering.output))}" alt="${escapeHtml(alt)}" loading="lazy">`;
  const notes = diagnostics.map((d) => `<br><span class="failed">${inlineCode(d)}</span>`).join("");
  const size = outcome.svg === undefined ? "" : `<br>${escapeHtml(sizeText(outcome))}`;
  return `<figure>${body}<figcaption>${caption}${size}${notes}</figcaption></figure>`;
}

function htmlComponent({ sample, outcomes }: GalleryModel["components"][number]): string {
  const { entry } = sample;
  const fields = manifestFields(entry);
  const props = propRows(entry);
  const meta = [
    ["since", entry.since],
    ...fields,
    ...(entry.deprecated === undefined ? [] : [["deprecated", JSON.stringify(entry.deprecated)]]),
  ]
    .map(([k, v]) => `<dt>${escapeHtml(k ?? "")}</dt><dd><code>${escapeHtml(v ?? "")}</code></dd>`)
    .join("");
  const propsHtml =
    props.length === 0
      ? `<p class="note">No props.</p>`
      : `<table><thead><tr><th>prop</th><th>type</th><th>required</th><th>description</th></tr></thead><tbody>${props
          .map(
            (p) =>
              `<tr><td><code>${escapeHtml(p.name)}</code></td><td><code>${escapeHtml(p.type)}</code></td><td>${p.required ? "yes" : "no"}</td><td>${inlineCode(p.description)}</td></tr>`,
          )
          .join("")}</tbody></table>`;
  const renders = outcomes
    .map((o) =>
      htmlFigure(
        o,
        `theme <code>${escapeHtml(o.theme)}</code> · <code>${escapeHtml(renderCommand(sample.fileName, o))}</code>`,
        `${entry.id}, every variant, theme ${o.theme}`,
      ),
    )
    .join("");
  return `<section class="card" id="${escapeHtml(anchor(entry))}">
<header><h3>${escapeHtml(entry.id)}</h3><span class="kind">${escapeHtml(entry.kind)}</span></header>
<p>${inlineCode(entry.description)}</p>
<ul class="chips" aria-label="variants">${entry.variants.map((v) => `<li>${escapeHtml(v)}</li>`).join("")}</ul>
<dl class="meta">${meta}</dl>
${propsHtml}
<div class="renders">${renders}</div>
<details><summary>Source: <code>${escapeHtml(sample.fileName)}</code></summary><pre>${escapeHtml(sample.source)}</pre></details>
</section>`;
}

