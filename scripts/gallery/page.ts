function mdThemes(model: GalleryModel): string {
  const { themeComparison: cmp, comparison } = model;
  const pipeline = THEMES.map((theme) =>
    comparison.outcomes.find(
      (o) => o.rendering.theme === theme && o.rendering.profile === "paper-single",
    ),
  ).filter((o): o is RenderOutcome => o !== undefined);
  // Three themes to a row keeps the figures readable.
  const rows = (outcomes: RenderOutcome[], file: string, alt: string) => {
    const lines: string[] = [];
    for (let i = 0; i < outcomes.length; i += 3) {
      lines.push(
        ...mdThemeRow(
          outcomes.slice(i, i + 3),
          file,
          (o) => `${alt}, theme ${o.theme}`,
          GALLERY_DIR,
        ),
      );
    }
    return lines;
  };
  return mdTopic("Themes", undefined, [
    "| theme | description | font set |",
    "| --- | --- | --- |",
    ...[...BUILTIN_THEMES.values()].map(
      (t) => `| ${mdCode(t.id)} | ${mdText(t.description ?? "")} | ${mdCode(t.fontSet.id)} |`,
    ),
    "",
    "## The structured Transformer under every theme",
    "",
    mdInline(THEME_COMPARISON_NOTE),
    "",
    ...rows(cmp.outcomes, cmp.source, "the structured Transformer"),
    `Source: ${mdLink(cmp.source, GALLERY_DIR)}`,
    "",
    "## The auto-layout pipeline under every theme",
    "",
    mdInline(
      `The same auto-layout figure (D2 with ELK, \`${comparison.source}\`) with \`--theme\` overrides on profile \`paper-single\`. This profile imposes a minimum font size (7pt), not a maximum; \`slides\` meets it and the pipeline fits the page. Its two collision warnings (\`geometry/label-collision\` and \`geometry/edge-crosses-label\`) are distinct from the \`geometry/exceeds-page-height\` error under \`presentation-16x9\`, whose larger spacing makes the pipeline taller than a slide.`,
    ),
    "",
    ...rows(pipeline, comparison.source, "the pipeline"),
    `Source: ${mdLink(comparison.source, GALLERY_DIR)}`,
    "",
  ]);
}

