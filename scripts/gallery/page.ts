function htmlComparison(comparison: GalleryModel["comparison"]): string {
  const rows = THEMES.map((theme) => {
    const cells = PROFILES.map((profile) => {
      const outcome = comparison.outcomes.find(
        (o) => o.rendering.theme === theme && o.rendering.profile === profile,
      );
      if (outcome === undefined) return "<td></td>";
      return `<td>${htmlFigure(outcome, `<code>${escapeHtml(renderCommand(comparison.source, outcome))}</code>`, `${comparison.source} with theme ${theme} and profile ${profile}`)}</td>`;
    }).join("");
    return `<tr><th><code>${escapeHtml(theme)}</code></th>${cells}</tr>`;
  }).join("");
  return `<p>${inlineCode(COMPARISON_NOTE)}</p>
<div style="overflow-x:auto"><table class="compare"><thead><tr><th>theme \\ profile</th>${PROFILES.map((p) => `<th><code>${escapeHtml(p)}</code></th>`).join("")}</tr></thead><tbody>${rows}</tbody></table></div>`;
}

