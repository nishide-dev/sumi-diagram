/** A figure under every theme (tones, a dimmed group) as a Markdown section. */
function mdThemeSample(
  title: string,
  note: string,
  { sample, outcomes }: GalleryModel["tones"],
  alt: string,
  level = "##",
): string[] {
  return [
    `${level} ${title}`,
    "",
    mdInline(note),
    "",
    ...mdThemeRow(outcomes, sample.fileName, (o) => `${alt}, theme ${o.theme}`, GALLERY_DIR),
    ...mdSource(sample.fileName, sample.source),
  ];
}

function mdComponent({ sample, outcomes }: GalleryModel["components"][number]): string {
  const { entry } = sample;
  const lines = [
    `# ${mdText(entry.id)}`,
    "",
    `[Gallery](../README.md) · ${mdInline(GENERATED_NOTE_SHORT)}`,
    "",
    mdInline(entry.description),
    "",
  ];
  const fields = [
    ["kind", entry.kind],
    ["variants", entry.variants.join(", ")],
    ["since", entry.since],
    ...manifestFields(entry),
  ];
  lines.push(fields.map(([k, v]) => `**${mdText(k ?? "")}**: ${mdCode(v ?? "")}`).join(" · "), "");
  const props = propRows(entry);
  if (props.length === 0) lines.push("No props.", "");
  else {
    lines.push("| prop | type | required | description |", "| --- | --- | --- | --- |");
    for (const p of props) {
      lines.push(
        `| ${mdCode(p.name)} | ${mdCode(p.type)} | ${p.required ? "yes" : "no"} | ${mdInline(p.description)} |`,
      );
    }
    lines.push("");
  }
  lines.push(
    ...mdThemeRow(
      outcomes,
      sample.fileName,
      (o) => `${entry.id}, theme ${o.theme}`,
      COMPONENTS_DIR,
    ),
    ...mdSource(sample.fileName, sample.source),
  );
  return lines.join("\n");
}

