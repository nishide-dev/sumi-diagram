/**
 * D2 source generation (design doc §2.4, §4.1, §6): a pure function of the
 * {@link FigureIR}. Same IR, byte-identical output.
 *
 * Every element gets its label, `class`, shape and complete effective style
 * written out explicitly, so the result never depends on D2's own defaults or
 * themes. Layout options and fonts are CLI flags, not part of the source.
 *
 * Quoting rules (verified against D2 v0.9.0, see #8):
 * - keys are always double-quoted: IDs may contain `-`, and an unquoted
 *   `n_a--b` parses as an edge;
 * - strings are double-quoted with `\`, `"` and `$` escaped (an unescaped `$`
 *   starts a substitution and fails to compile), line breaks as `\n` and tabs
 *   as `\t`. Other control characters become U+FFFD, as D2 renders them.
 */

import { iconBox } from "../assets/draw";
import type { ElementKey } from "../core/check-state";
import type { GroupLabelPosition } from "../core/figure/schema";
import { getProfile } from "../core/profile/builtin";
import { KIND_DEFAULTS, type ResolvedStyle, type StyleLength } from "../core/theme/style";
import { type NodePadding, nodeSize } from "../layout/structured/sizing";
import type { EdgeIR, FigureIR, GroupIR, NodeIR } from "./ir";

const INDENT = "  ";

const EDGE_OPERATORS: Readonly<Record<EdgeIR["direction"], string>> = {
  forward: "->",
  backward: "<-",
  both: "<->",
  none: "--",
};

/**
 * Where a group's label goes (#31). D2 centers it at the top by default, where
 * ELK routes edges entering the container from above (into the first child,
 * which ELK also centers); at the top-left corner it is out of their way in
 * most layouts. D2 still reserves the room for it above the children. This is
 * the default; `labelAt` (#127) picks another position inside the border.
 */
const GROUP_LABEL_NEAR = "top-left";

/** D2's `label.near` for each `groups[].labelAt` (#127, verified with D2 v0.9.0 in #124). */
const GROUP_LABEL_NEAR_AT: Readonly<Record<GroupLabelPosition, string>> = {
  "top-left": "top-left",
  top: "top-center",
  "top-right": "top-right",
  "bottom-left": "bottom-left",
  bottom: "bottom-center",
  "bottom-right": "bottom-right",
};

/** Generates the D2 source for a figure. */
export function generateD2(ir: FigureIR): string {
  const profile = getProfile(ir.meta.profileId);
  if (profile === undefined)
    throw new Error(`internal error: unknown profile ${ir.meta.profileId}`);
  const padding: NodePadding = {
    x: profile.layout.nodePaddingX.pt * 2,
    y: profile.layout.nodePaddingY.pt * 2,
  };
  const out: string[] = [
    `# Generated by Sumi from figure "${ir.meta.id}". Do not edit; change the .sumi.yaml instead.`,
    `direction: ${ir.meta.direction}`,
  ];
  const write = (depth: number, line: string) => out.push(INDENT.repeat(depth) + line);

  const writeObject = (key: ElementKey, depth: number) => {
    const element = ir.elements.get(key);
    if (element === undefined || element.kind === "edge") {
      throw new Error(`internal error: ${key} is not a node or group`);
    }
    // A caption (#130) is written with its group, as the container around it.
    if (element.kind === "node" && element.captionOf !== undefined) return;
    if (element.kind === "group" && element.caption !== undefined) {
      writeCaption(element.caption, depth, () => writeElement(element, depth + 1));
      return;
    }
    writeElement(element, depth);
  };

  /**
   * A group's caption (#130, design doc §6.32): a transparent container
   * around the group whose label is the caption, at the bottom centre inside
   * it, so in the container's padding below the group's border. Not
   * `outside-bottom-center` (#124): with it, D2 v0.9.0 moves the container's
   * contents up after the ELK layout but not the far ends of edges leaving
   * the container, which then run askew. The caption node's own style gives
   * the text; the container draws nothing.
   */
  const writeCaption = (key: ElementKey, depth: number, writeGroup: () => void) => {
    const caption = ir.elements.get(key);
    if (caption?.kind !== "node") throw new Error(`internal error: ${key} is not a caption node`);
    out.push("");
    write(depth, `${d2String(caption.d2Key)}: {`);
    const body = depth + 1;
    write(body, `label: ${d2String(caption.label)}`);
    write(body, `class: ${classList(key, "node")}`);
    write(body, "shape: rectangle");
    write(body, "label.near: bottom-center");
    // No fill (a container's default) and no border: only the text shows.
    const none = { pt: 0, units: 0 };
    writeStyle(
      { ...caption.style, fill: KIND_DEFAULTS.group.fill, strokeWidth: none },
      body,
      write,
    );
    writeGroup();
    write(depth, "}");
  };

  const writeElement = (element: NodeIR | GroupIR, depth: number) => {
    const { key } = element;
    out.push("");
    write(depth, `${d2String(element.d2Key)}: {`);
    const body = depth + 1;
    write(body, `label: ${d2String(element.label)}`);
    write(body, `class: ${classList(key, element.kind)}`);
    // D2 rejects a text shape without a label: an icon on a label node (#94)
    // is a rectangle placeholder in the label's (transparent) style instead.
    const textIcon =
      element.kind === "node" && element.icon !== undefined && element.shape === "text";
    write(body, `shape: ${textIcon ? "rectangle" : element.shape}`);
    if (element.kind === "group") {
      const near =
        element.labelAt === undefined ? GROUP_LABEL_NEAR : GROUP_LABEL_NEAR_AT[element.labelAt];
      write(body, `label.near: ${near}`);
    }
    // D2 otherwise moves labels outside undersized explicit rectangles. Keep
    // outline labels centered so composition can translate into the safe area.
    if (element.kind === "node" && element.render !== undefined)
      write(body, "label.near: center-center");
    if (element.kind === "node") writeSize(element, body, write, padding);
    writeStyle(element.style, body, write);
    if (element.kind === "group") for (const child of element.children) writeObject(child, body);
    write(depth, "}");
  };

  for (const key of ir.roots) writeObject(key, 0);

  for (const edge of ir.edges) {
    const from = objectPath(ir, edge.from);
    const to = objectPath(ir, edge.to);
    out.push("");
    write(0, `${from} ${EDGE_OPERATORS[edge.direction]} ${to}: {`);
    write(1, `label: ${d2String(edge.label)}`);
    write(1, `class: ${classList(edge.key, "edge")}`);
    writeStyle(edge.style, 1, write);
    for (const [end, shape] of [
      ["source-arrowhead", edge.sourceArrowhead],
      ["target-arrowhead", edge.targetArrowhead],
    ] as const) {
      if (shape === undefined) continue;
      write(1, `${end}: {`);
      write(2, `shape: ${shape}`);
      write(2, `style.filled: ${edge.style.filled}`);
      write(1, "}");
    }
    write(0, "}");
  }

  return `${out.join("\n")}\n`;
}

type Write = (depth: number, line: string) => void;

function writeSize(node: NodeIR, depth: number, write: Write, padding: NodePadding): void {
  // An icon node (#94) has no label for D2 to size it by: it gets the size
  // the structured engine gives it (the icon's 1 em square, padded).
  const icon = iconBox(node);
  const natural =
    icon === undefined || (node.width !== undefined && node.height !== undefined)
      ? undefined
      : nodeSize(node, icon, padding);
  const width = node.width?.units ?? natural?.width;
  const height = node.height?.units ?? natural?.height;
  if (width !== undefined) write(depth, `width: ${integer(width)}`);
  if (height !== undefined) write(depth, `height: ${integer(height)}`);
}

/** Writes every property of a resolved style (design doc §4.1). */
function writeStyle(style: ResolvedStyle, depth: number, write: Write): void {
  const shape = style.kind !== "edge";
  const entries: [string, string | false][] = [
    // On an edge, D2 draws the fill as a padded box behind the label (#31).
    ["fill", d2String(style.fill)],
    ["stroke", d2String(style.stroke)],
    ["stroke-width", units(style.strokeWidth)],
    ["stroke-dash", integer(style.strokeDash)],
    ["border-radius", shape && units(style.radius)],
    ["opacity", String(style.opacity)],
    ["font-size", units(style.fontSize)],
    ["font-color", d2String(style.fontColor)],
    ["bold", String(style.bold)],
    ["italic", String(style.italic)],
    // D2 only knows `mono`; the regular typeface comes from the font set (CLI flags).
    ["font", style.mono && "mono"],
  ];
  write(depth, "style: {");
  for (const [name, value] of entries) if (value !== false) write(depth + 1, `${name}: ${value}`);
  write(depth, "}");
}

/** `class: ["sumi-k-<enc>"; "sumi-kind-<kind>"]` (design doc §2.4). */
function classList(key: ElementKey, kind: "node" | "group" | "edge"): string {
  return `[${d2String(elementClass(key))}; ${d2String(`sumi-kind-${kind}`)}]`;
}

/**
 * The reverse-lookup class of an element (design doc §2.4): `sumi-k-` plus the
 * ElementKey with `:` → `--` and `#` → `_`, e.g. `n:api` → `sumi-k-n--api`,
 * `e:#3` → `sumi-k-e--_3`.
 */
export function elementClass(key: ElementKey): string {
  return `sumi-k-${key.replace(":", "--").replace("#", "_")}`;
}

/** The full D2 path of a node or group, e.g. `"g_backend"."n_api"`. */
function objectPath(ir: FigureIR, key: ElementKey): string {
  const element = ir.elements.get(key);
  if (element === undefined || element.kind === "edge") {
    throw new Error(`internal error: edge endpoint ${key} is not a node or group`);
  }
  return element.d2Path.map(d2String).join(".");
}

function units(length: StyleLength): string {
  return integer(length.units);
}

function integer(value: number): string {
  if (!Number.isInteger(value)) throw new Error(`internal error: ${value} is not an integer`);
  return String(value);
}

// biome-ignore lint/suspicious/noControlCharactersInRegex: control characters are what we replace
const CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g;

/**
 * Quotes text as a D2 double-quoted string. Escapes `\`, `"` and `$`, writes
 * line breaks (`\r\n`, `\r`, `\n`) as `\n` and tabs as `\t`, and replaces
 * other control characters with U+FFFD.
 */
export function d2String(text: string): string {
  const escaped = text
    .replace(/[\\"$]/g, (c) => `\\${c}`)
    .replace(/\r\n?|\n/g, "\\n")
    .replace(/\t/g, "\\t")
    .replace(CONTROL, "\uFFFD");
  return `"${escaped}"`;
}
