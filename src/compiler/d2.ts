/**
 * D2 source generation (design doc §2.4, §4.1, §6): a pure function of the
 * {@link FigureIR}. Same IR, byte-identical output.
 *
 * Every element gets its label, `class`, shape and complete effective style
 * written out explicitly, so the result never depends on D2's own defaults or
 * themes. Layout options and fonts are CLI flags, not part of the source.
 *
 * Quoting rules (verified against D2 v0.9.0, see #8):
 * - keys are always double-quoted: IDs may contain `-`, and an unquoted
 *   `n_a--b` parses as an edge;
 * - strings are double-quoted with `\`, `"` and `$` escaped (an unescaped `$`
 *   starts a substitution and fails to compile), line breaks as `\n` and tabs
 *   as `\t`. Other control characters become U+FFFD, as D2 renders them.
 */

import type { ElementKey } from "../core/check-state";
import type { ResolvedStyle, StyleLength } from "../core/theme/style";
import type { EdgeIR, FigureIR, NodeIR } from "./ir";

const INDENT = "  ";

const EDGE_OPERATORS: Readonly<Record<EdgeIR["direction"], string>> = {
  forward: "->",
  backward: "<-",
  both: "<->",
  none: "--",
};

/** Generates the D2 source for a figure. */
export function generateD2(ir: FigureIR): string {
  const out: string[] = [
    `# Generated by Sumi from figure "${ir.meta.id}". Do not edit; change the .sumi.yaml instead.`,
    `direction: ${ir.meta.direction}`,
  ];
  const write = (depth: number, line: string) => out.push(INDENT.repeat(depth) + line);

  const writeObject = (key: ElementKey, depth: number) => {
    const element = ir.elements.get(key);
    if (element === undefined || element.kind === "edge") {
      throw new Error(`internal error: ${key} is not a node or group`);
    }
    out.push("");
    write(depth, `${d2String(element.d2Key)}: {`);
    const body = depth + 1;
    write(body, `label: ${d2String(element.label)}`);
    write(body, `class: ${classList(key, element.kind)}`);
    write(body, `shape: ${element.shape}`);
    if (element.kind === "node") writeSize(element, body, write);
    writeStyle(element.style, body, write);
    if (element.kind === "group") for (const child of element.children) writeObject(child, body);
    write(depth, "}");
  };

  for (const key of ir.roots) writeObject(key, 0);

  for (const edge of ir.edges) {
    const from = objectPath(ir, edge.from);
    const to = objectPath(ir, edge.to);
    out.push("");
    write(0, `${from} ${EDGE_OPERATORS[edge.direction]} ${to}: {`);
    write(1, `label: ${d2String(edge.label)}`);
    write(1, `class: ${classList(edge.key, "edge")}`);
    writeStyle(edge.style, 1, write);
    for (const [end, shape] of [
      ["source-arrowhead", edge.sourceArrowhead],
      ["target-arrowhead", edge.targetArrowhead],
    ] as const) {
      if (shape === undefined) continue;
      write(1, `${end}: {`);
      write(2, `shape: ${shape}`);
      write(2, `style.filled: ${edge.style.filled}`);
      write(1, "}");
    }
    write(0, "}");
  }

  return `${out.join("\n")}\n`;
}

type Write = (depth: number, line: string) => void;

function writeSize(node: NodeIR, depth: number, write: Write): void {
  if (node.width !== undefined) write(depth, `width: ${units(node.width)}`);
  if (node.height !== undefined) write(depth, `height: ${units(node.height)}`);
}

/** Writes every property of a resolved style (design doc §4.1). */
function writeStyle(style: ResolvedStyle, depth: number, write: Write): void {
  const shape = style.kind !== "edge";
  const entries: [string, string | false][] = [
    ["fill", shape && d2String(style.fill)],
    ["stroke", d2String(style.stroke)],
    ["stroke-width", units(style.strokeWidth)],
    ["stroke-dash", integer(style.strokeDash)],
    ["border-radius", shape && units(style.radius)],
    ["opacity", String(style.opacity)],
    ["font-size", units(style.fontSize)],
    ["font-color", d2String(style.fontColor)],
    ["bold", String(style.bold)],
    ["italic", String(style.italic)],
    // D2 only knows `mono`; the regular typeface comes from the font set (CLI flags).
    ["font", style.mono && "mono"],
  ];
  write(depth, "style: {");
  for (const [name, value] of entries) if (value !== false) write(depth + 1, `${name}: ${value}`);
  write(depth, "}");
}

/** `class: ["sumi-k-<enc>"; "sumi-kind-<kind>"]` (design doc §2.4). */
function classList(key: ElementKey, kind: "node" | "group" | "edge"): string {
  return `[${d2String(elementClass(key))}; ${d2String(`sumi-kind-${kind}`)}]`;
}

/**
 * The reverse-lookup class of an element (design doc §2.4): `sumi-k-` plus the
 * ElementKey with `:` → `--` and `#` → `_`, e.g. `n:api` → `sumi-k-n--api`,
 * `e:#3` → `sumi-k-e--_3`.
 */
export function elementClass(key: ElementKey): string {
  return `sumi-k-${key.replace(":", "--").replace("#", "_")}`;
}

/** The full D2 path of a node or group, e.g. `"g_backend"."n_api"`. */
function objectPath(ir: FigureIR, key: ElementKey): string {
  const element = ir.elements.get(key);
  if (element === undefined || element.kind === "edge") {
    throw new Error(`internal error: edge endpoint ${key} is not a node or group`);
  }
  return element.d2Path.map(d2String).join(".");
}

function units(length: StyleLength): string {
  return integer(length.units);
}

function integer(value: number): string {
  if (!Number.isInteger(value)) throw new Error(`internal error: ${value} is not an integer`);
  return String(value);
}

// biome-ignore lint/suspicious/noControlCharactersInRegex: control characters are what we replace
const CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g;

/**
 * Quotes text as a D2 double-quoted string. Escapes `\`, `"` and `$`, writes
 * line breaks (`\r\n`, `\r`, `\n`) as `\n` and tabs as `\t`, and replaces
 * other control characters with U+FFFD.
 */
export function d2String(text: string): string {
  const escaped = text
    .replace(/[\\"$]/g, (c) => `\\${c}`)
    .replace(/\r\n?|\n/g, "\\n")
    .replace(/\t/g, "\\t")
    .replace(CONTROL, "\uFFFD");
  return `"${escaped}"`;
}
