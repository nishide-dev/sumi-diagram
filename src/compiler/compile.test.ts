import { describe, expect, test } from "bun:test";
import { join } from "node:path";
import { getProfile } from "../core/profile/builtin";
import { toD2LayoutArgs } from "../core/profile/d2";
import { fontSetArgs, getFontSet } from "../core/theme/fonts";
import { compileFigure, expectD2Figure } from "./compile";
import { FIXTURES_DIR } from "./testing";

describe("compileFigure", () => {
  test("returns the IR, D2 source, layout and font arguments", async () => {
    const text = await Bun.file(join(FIXTURES_DIR, "compile/builtins.sumi.yaml")).text();
    const result = compileFigure(text);
    if (!result.ok) throw new Error(JSON.stringify(result.diagnostics));
    const { ir, d2Source, layout, fontSet, sourceMap } = expectD2Figure(result.value);
    expect(result.diagnostics).toEqual([]);
    expect(d2Source.startsWith("# Generated by Sumi")).toBe(true);
    expect(d2Source).toContain("direction: down\n");
    const profile = getProfile("paper-double");
    const font = getFontSet("sumi/biz-ud-gothic");
    if (!profile || !font) throw new Error("missing built-ins");
    expect(layout).toEqual(toD2LayoutArgs(profile));
    expect(fontSet).toEqual({ id: "sumi/biz-ud-gothic", args: fontSetArgs(font) });
    expect(sourceMap).toBe(ir.sourceMap);
  });

  test("fails with diagnostics and generates nothing when a check fails", async () => {
    const dir = join(FIXTURES_DIR, "figures/invalid");
    const files = [...new Bun.Glob("*.sumi.yaml").scanSync(dir)].sort();
    expect(files.length).toBeGreaterThan(0);
    for (const file of files) {
      const result = compileFigure(await Bun.file(join(dir, file)).text(), { file });
      expect(result.ok).toBe(false);
      expect(result).not.toHaveProperty("value");
      expect(result.diagnostics.some((d) => d.severity === "error")).toBe(true);
    }
  });

  test("reports problems from every checking stage", () => {
    const result = compileFigure(`version: 1
figure: { id: broken, theme: minimal, profile: nope }
nodes:
  - { id: a, component: box }
  - { id: b, component: label }
edges:
  - { from: a, to: c }
`);
    expect(result.ok).toBe(false);
    expect(result.diagnostics.map((d) => d.code)).toEqual([
      "ref/unknown-endpoint",
      "component/missing-label",
      "profile/unknown",
    ]);
  });
});
